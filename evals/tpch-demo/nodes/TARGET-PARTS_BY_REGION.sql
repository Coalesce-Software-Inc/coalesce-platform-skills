SELECT
    R."R_REGIONKEY"     AS R_REGIONKEY,
    R."R_NAME"          AS R_NAME,
    P."P_PARTKEY"       AS P_PARTKEY,
    P."P_NAME"          AS P_NAME,
    P."P_MFGR"          AS P_MFGR,
    P."P_BRAND"         AS P_BRAND,
    P."P_TYPE"          AS P_TYPE,
    P."P_SIZE"          AS P_SIZE,
    L."L_QUANTITY"      AS L_QUANTITY,
    L."L_EXTENDEDPRICE" AS L_EXTENDEDPRICE,
    O."O_ORDERKEY"      AS O_ORDERKEY,
    O."O_ORDERDATE"     AS O_ORDERDATE
FROM {{ ref('TARGET', 'STG_PART') }} P
INNER JOIN {{ ref('SRC', 'LINEITEM') }} L
    ON P.P_PARTKEY = L.L_PARTKEY
INNER JOIN {{ ref('TARGET', 'STG_ORDERS') }} O
    ON L.L_ORDERKEY = O.O_ORDERKEY
INNER JOIN {{ ref('TARGET', 'STG_CUSTOMER') }} C
    ON O.O_CUSTKEY = C.C_CUSTKEY
INNER JOIN {{ ref('TARGET', 'STG_NATION') }} N
    ON C.C_NATIONKEY = N.N_NATIONKEY
INNER JOIN {{ ref('TARGET', 'STG_REGION') }} R
    ON N.N_REGIONKEY = R.R_REGIONKEY
