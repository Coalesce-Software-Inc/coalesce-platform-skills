@id("7b2e4f16-9a3c-4d81-b6e0-1f8c5a2d9e47")
@nodeType("0016cdc3-eacd-4610-9147-8217aeeea42c")

SELECT
    NS.N_NATIONKEY,
    NS.N_NAME,
    NS.R_REGIONKEY,
    NS.R_NAME,
    NS.CUSTOMER_COUNT,
    COUNT(DISTINCT O."O_ORDERKEY")        AS ORDER_COUNT,
    SUM(L."L_EXTENDEDPRICE"
        * (1 - L."L_DISCOUNT"))           AS TOTAL_REVENUE,
    AVG(O."O_TOTALPRICE")                 AS AVG_ORDER_VALUE
FROM {{ ref('TARGET', 'NATION_SUMMARY') }} NS
LEFT JOIN {{ ref('TARGET', 'STG_CUSTOMER') }} C
    ON NS.N_NATIONKEY = C.C_NATIONKEY
LEFT JOIN {{ ref('TARGET', 'STG_ORDERS') }} O
    ON C.C_CUSTKEY = O.O_CUSTKEY
LEFT JOIN {{ ref('TARGET', 'STG_LINEITEM') }} L
    ON O.O_ORDERKEY = L.L_ORDERKEY
GROUP BY
    NS.N_NATIONKEY,
    NS.N_NAME,
    NS.R_REGIONKEY,
    NS.R_NAME,
    NS.CUSTOMER_COUNT
