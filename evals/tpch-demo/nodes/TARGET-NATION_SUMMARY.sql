SELECT
    N."N_NATIONKEY"      AS N_NATIONKEY,
    N."N_NAME"           AS N_NAME,
    R."R_REGIONKEY"      AS R_REGIONKEY,
    R."R_NAME"           AS R_NAME,
    COUNT(C."C_CUSTKEY") AS CUSTOMER_COUNT
FROM {{ ref('TARGET', 'STG_NATION') }} N
INNER JOIN {{ ref('TARGET', 'STG_REGION') }} R
    ON N.N_REGIONKEY = R.R_REGIONKEY
LEFT JOIN {{ ref('TARGET', 'STG_CUSTOMER') }} C
    ON N.N_NATIONKEY = C.C_NATIONKEY
GROUP BY
    N.N_NATIONKEY,
    N.N_NAME,
    R.R_REGIONKEY,
    R.R_NAME
